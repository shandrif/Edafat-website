"""Turn the scraped Cognivra page (tools/fetch_cognivra.js output) into js/data.js + optimised images.
Usage:  python3 -I tools/build_brands.py <raw-dir>
Everything here is *data from the source page*; the only editorial additions are marked DERIVED
(items split out of a one-sentence "flagship" description) and the brand tint colours."""
import json, os, re, sys, shutil
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = sys.argv[1]
src = json.load(open(os.path.join(RAW, "cognivra.json")))
os.makedirs(os.path.join(ROOT, "img/brands"), exist_ok=True)
os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
shutil.copy(os.path.join(RAW, "cognivra.json"), os.path.join(ROOT, "data/cognivra-source.json"))

# domain -> (slug, display name, tint colours [dark, light])
BRANDS = {
    "alpepragas.com":   ("alpe-pragas", "Alpe Pragas",   ["#4a2234", "#8a3b55"]),
    "mamiscaffe.com":   ("mamis-caffe", "Mamis Caffè",   ["#3d261b", "#7d4d33"]),
    "alps-coffee.it":   ("alps-coffee", "Alps Coffee",   ["#26343a", "#53727c"]),
    "alpeker.it":       ("alpeker",     "Alpeker",       ["#1f3a52", "#4a82ad"]),
    "pan.it":           ("pan",         "Pan",           ["#5c3a0e", "#b98428"]),
    "rieper.com":       ("rieper",      "Rieper",        ["#413d1f", "#8d8239"]),
    "vog-products.it":  ("vog-products","VOG Products",  ["#27432a", "#5f9247"]),
    "oberhoeller.com":  ("oberhoeller", "Oberhöller",    ["#35201a", "#6e4330"]),
    "alplsparkling.com":("alpl",        "ALPL Sparkling",["#4d4212", "#d2ae35"]),
}
# DERIVED: the source gives a one-sentence "flagship" description for these brands; split into items.
DERIVED = {
    "alps-coffee": (["Espresso blends", "100% Arabica blends", "Whole beans", "Ground coffee", "Coffee pods"], "Organic and Fairtrade."),
    "alpeker":     (["Frozen yogurt tubs", "Frozen yogurt sticks", "Greek frozen yogurt", "Frozen kefir"], ""),
    "pan":         (["Apple strudel", "Puff pastry snacks", "Canapés", "Mini pizzas"], ""),
    "rieper":      (["Soft wheat flour", "Rye flour", "Wholemeal flour", "Pizza flour", "Organic flours", "Polenta", "Bread mixes"], ""),
    "vog-products":(["NFC juices", "Concentrates", "Purées", "Dried apples", "IQF fruit"], ""),
    "oberhoeller": (["Chocolate bars", "Spreads", "Dragées", "Nougat", "Seasonal gifts"], "More than 70 products."),
    "alpl":        (["ALPL Golden Times Alcohol Free"], "For aperitifs and zero-proof cocktails."),
}
CATEGORIES = ["Jams & preserves", "Coffee", "Dairy & frozen", "Bakery & fruit ingredients", "Chocolate", "Alcohol-free beverages"]

def sentence(s):
    s = s.lower(); return s[:1].upper() + s[1:]

def save_photo(name, slug):
    im = Image.open(os.path.join(RAW, "img", name)).convert("RGB")
    im.thumbnail((1300, 1300)); out = f"img/brands/{slug}-photo.webp"
    im.save(os.path.join(ROOT, out), quality=82, method=6); return out, im.size

def save_logo(name, slug):
    im = Image.open(os.path.join(RAW, "img", name)).convert("RGBA")
    bb = im.getchannel("A").point(lambda v: 255 if v > 8 else 0).getbbox()
    if bb: im = im.crop(bb)
    pad = int(max(im.size) * .02); canvas = Image.new("RGBA", (im.width + pad * 2, im.height + pad * 2), (0, 0, 0, 0)); canvas.paste(im, (pad, pad))
    canvas.thumbnail((640, 640), Image.LANCZOS); out = f"img/brands/{slug}-logo.webp"
    canvas.save(os.path.join(ROOT, out), quality=92, method=6); return out, canvas.size

brands = []
for c in src["cards"]:
    dom = re.sub(r"^https?://(www\.)?|/$", "", c["url"])
    slug, name, tint = BRANDS[dom]
    lines = c["lines"]
    tag = sentence(lines[0]); meta = [m.strip() for m in lines[1].split("·")]
    place, extra = meta[0], meta[1:]
    flag_i = next(i for i, l in enumerate(lines) if l.upper().startswith("FLAGSHIP"))
    blurb = " ".join(lines[2:flag_i]); tail = lines[flag_i + 1:]
    tail = [t for t in tail if not t.endswith("↗")]
    if lines[flag_i].upper() == "FLAGSHIP RANGE":
        items, note = tail, ""
    else:
        items, note = DERIVED[slug]
    photo, psize = save_photo(c["photo"] and src["files"][c["photo"]], slug)
    logo, lsize = save_logo(src["files"][c["logo"]], slug)
    brands.append({"slug": slug, "name": name, "category": c["category"], "tag": tag, "place": place, "facts": extra,
                   "blurb": blurb, "note": note, "items": [{"n": n} for n in items], "url": c["url"],
                   "photo": photo, "photoSize": list(psize), "logo": logo, "logoSize": list(lsize), "tint": tint})
    print(f"{name:16} {c['category']:28} items={len(items):2} photo={psize} logo={lsize}")

data = {"source": src["source"], "fetchedAt": src["fetchedAt"], "categories": CATEGORIES,
        "context": " ".join(src["demand"][1:2]), "sectors": [s for s in src["demand"][2:]], "brands": brands}
js = ("/* Generated by tools/build_brands.py from " + src["source"] + "\n   Re-run tools/fetch_cognivra.js + tools/build_brands.py to refresh. Do not edit by hand. */\n"
      "window.SITE = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
open(os.path.join(ROOT, "js/data.js"), "w").write(js)
print("brands:", len(brands), " items:", sum(len(b["items"]) for b in brands))
