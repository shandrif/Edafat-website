"""Assemble js/ar.js (all Arabic text) from tools/i18n/*.py and js/data.js.
Usage: python3 -I tools/build_arabic.py
Descriptions are matched to the translation lists by order of first appearance per brand (see the numbered comments in d_*.py);
the script checks that every number in an English description also appears in its Arabic text, to catch misalignment."""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools/i18n"))
from names_ar import NAMES
from ui_ar import *
from d_alpe import D as ALPE
from d_others import MAMIS, ALPS, ALPEKER, VOG, OBER, ALPL
from d_pan import PAN
from cartons_ar import CARTONS

src = open(os.path.join(ROOT, "js/data.js")).read()
site = json.loads(src[src.index("{"): src.rindex("}") + 1])
LISTS = {"alpe-pragas": ALPE, "mamis-caffe": MAMIS, "alps-coffee": ALPS, "alpeker": ALPEKER, "pan": PAN, "vog-products": VOG, "oberhoeller": OBER, "alpl": ALPL}

# descriptions: first-appearance order, attributed to the first brand that uses the text
seen, order = set(), {}
for b in site["brands"]:
    for it in b["items"]:
        if it["d"] and it["d"] not in seen: seen.add(it["d"]); order.setdefault(b["slug"], []).append(it["d"])
descs, problems = {}, []
for slug, en_list in order.items():
    ar = LISTS[slug]
    if len(ar) != len(en_list): sys.exit(f"{slug}: {len(en_list)} English descriptions but {len(ar)} Arabic")
    for i, (en, a) in enumerate(zip(en_list, ar)):
        descs[en] = a
        nums = set(re.findall(r"\d+(?:[.,]\d+)?", en))
        miss = [n for n in nums if n not in a and n.replace(",", ".") not in a]
        if miss and len(miss) > 0: problems.append((slug, i, miss, en[:50], a[:40]))
names = {}
for b in site["brands"]:
    for it in b["items"]:
        n = NAMES.get(it["n"])
        if n is None: sys.exit("missing name translation: " + it["n"])
        names[it["n"]] = n.replace("كواركـ", "كوارك")
for b in site["brands"]:
    for it in b["items"]:
        if it["g"] not in GROUPS: sys.exit("missing group: " + it["g"])
        if it.get("c") and it["c"] not in CARTONS: sys.exit("missing carton: " + it["c"])
print("alignment warnings (number missing in Arabic):", len(problems))
for p in problems[:25]: print("  ", p)

AR = {"ui": UI, "brandNames": BRAND_NAMES, "brands": BRANDS, "categories": CATEGORIES, "sectors": SECTORS, "groups": GROUPS, "names": names, "descs": descs,
      "cartons": CARTONS, "context": CONTEXT, "formatsTitle": FORMATS_TITLE, "formatsIntro": FORMATS_INTRO, "formats": FORMATS, "occasionsTitle": OCC_TITLE, "occasionsIntro": OCC_INTRO,
      "occasions": OCCASIONS, "addr": ADDR}
open(os.path.join(ROOT, "js/ar.js"), "w").write("/* Generated by tools/build_arabic.py from tools/i18n/*.py. Arabic text is a translation by the site builder: have a native speaker review it. */\nwindow.AR = " + json.dumps(AR, ensure_ascii=False, indent=0) + ";\n")
print("names", len(names), "descs", len(descs), "bytes", os.path.getsize(os.path.join(ROOT, "js/ar.js")))
