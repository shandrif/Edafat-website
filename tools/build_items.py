"""Build js/data.js + optimised images from the per-brand crawls (tools/crawl/*.js -> <raw>/<slug>.json + <raw>/img/<slug>/*).
Usage: python3 -I tools/build_items.py <raw-crawl-dir> <raw-cognivra-dir>
- <raw-cognivra-dir> holds cognivra.json (the Food & Beverage page: brand blurbs, logos, category photos) from tools/fetch_cognivra.js
Every product photo and text comes from the brand's own website. Nothing is drawn or generated.
Item photos are saved as JPEG on a white canvas (flattening transparent PNGs) so cards look consistent."""
import json, os, re, sys, shutil, html
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRAWL, COG = sys.argv[1], sys.argv[2]
OUT = os.path.join(ROOT, "img/items"); shutil.rmtree(OUT, ignore_errors=True); os.makedirs(OUT)
os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
base = json.load(open(os.path.join(ROOT, "data/cognivra-source.json")))     # produced earlier by fetch_cognivra.js
brands_prev = {b["slug"]: b for b in json.load(open(os.path.join(ROOT, "data/brands.json")))["brands"]} if os.path.exists(os.path.join(ROOT, "data/brands.json")) else None

# the brand-level data (name, blurb, logo, photo...) was generated by build_brands.py into js/data.js: reuse it
src = open(os.path.join(ROOT, "js/data.js")).read()
site = json.loads(src[src.index("{"): src.rindex("}") + 1])
brands = {b["slug"]: b for b in site["brands"]}

SKIP = {  # not products: accessories / gift sets / wrong pages
    "alpe-pragas": re.compile(r"wooden tray|gift|box\b|kit\b|set\b", re.I),
}
def clean(s): return re.sub(r"\s+", " ", html.unescape(s or "")).strip()
def title(s):
    s = clean(s)
    return s if re.search(r"[a-z]", s) else s.title()       # ALL CAPS -> Title Case, otherwise keep the brand's own casing

def save(slug, idx, src_path):
    im = Image.open(src_path)
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA"); bg = Image.new("RGBA", im.size, (255, 255, 255, 255)); bg.alpha_composite(im); im = bg
    im = im.convert("RGB"); im.thumbnail((720, 720), Image.LANCZOS)
    name = f"{slug}-{idx:03d}.jpg"; im.save(os.path.join(OUT, name), quality=80, optimize=True, progressive=True)
    return f"img/items/{name}", list(im.size)

total = 0
for f in sorted(os.listdir(CRAWL)):
    if not f.endswith(".json"): continue
    j = json.load(open(os.path.join(CRAWL, f))); slug = j["slug"]; b = brands[slug]; items = []
    for i, it in enumerate(j["items"]):
        if not it.get("file"): continue
        if slug in SKIP and SKIP[slug].search(it["n"]): continue
        path, size = save(slug, len(items), os.path.join(CRAWL, "img", it["file"]))
        items.append({"n": title(it["n"]), "g": clean(it.get("g", "")), "d": clean(it.get("d", "")), "img": path, "size": size, "u": it.get("u", b["url"])})
    b["items"] = items; b["itemSource"] = j["source"]; b["groups"] = sorted({x["g"] for x in items if x["g"]}, key=lambda g: -sum(1 for x in items if x["g"] == g))
    total += len(items); print(f"{slug:13} {len(items):3} items, groups: {', '.join(b['groups'])}")

site["brands"] = [brands[b["slug"]] for b in site["brands"]]
js = ("/* Generated by tools/build_brands.py (brand profiles from cognivra.net) + tools/build_items.py (every item, photo and text from the brand's own website).\n"
      "   Do not edit by hand: re-run the crawlers to refresh. */\nwindow.SITE = " + json.dumps(site, ensure_ascii=False, indent=1) + ";\n")
open(os.path.join(ROOT, "js/data.js"), "w").write(js)
print("total items:", total)
